/**
 * Time formatting shared by the routines page. Three surfaces show the same
 * wall clock — the next-due line in the editor, the routine list row and a run
 * card — so the format lives here once instead of being copied per component.
 */
export function formatWhen(ms?: number | null): string {
  if (!ms) return "—";
  try {
    return new Date(ms).toLocaleString();
  } catch {
    return "—";
  }
}

export function formatInterval(secs: number): string {
  if (secs < 60) return `${secs}s`;
  if (secs < 3600) return `${Math.round(secs / 60)}m`;
  if (secs < 86400) return `${Math.round(secs / 3600)}h`;
  return `${Math.round(secs / 86400)}d`;
}
