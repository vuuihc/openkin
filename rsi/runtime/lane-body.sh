# shellcheck shell=bash
# lane-body.sh — the hand-off body a committed lane can still carry when its worker died early.
#
# A worker can finish its code, commit it and return before it writes
# state/lanes/<slug>.pr-body.md (watchdog, budget, a session that stopped after the last commit).
# The lane's body-dependent seams then read a missing file, the first of them fails the round, and
# a clean, tested commit is left unpushed: the operator sees `failed "" "claim check: ... no
# output"` with no PR. This helper writes a clearly labelled partial body for that case so the
# merge lane — not the body seams — decides what the commit is worth. It never touches a body the
# worker did write, and it writes nothing when there is no commit to hand off.
#
# Sourced by lane.sh and by rsi/runtime/tests/test-lane-partial-handoff.sh; no top-level side
# effects. The only external tool it may run is the git binary passed in as $5: no network, no gh.

# ensure_handoff_body <state-dir> <lane-n> <item> <worktree> <git-binary> <slug>
#   worker body present and non-empty -> print its path, return 0, never modify it
#   body missing + at least one commit  -> write <state-dir>/lanes/<n>.pr-body.fallback.md,
#                                          print its path, return 0
#   body missing + no commit            -> print nothing, return 1
ensure_handoff_body() {
  local state="$1" n="$2" item="$3" wt="$4" git="$5" slug="$6"
  local body="$state/lanes/$slug.pr-body.md"
  local fallback="$state/lanes/$n.pr-body.fallback.md"
  local ahead
  # A worker body is authoritative: same path, same bytes, no fallback beside it.
  if [ -s "$body" ]; then printf '%s\n' "$body"; return 0; fi
  # Only a committed lane has anything to hand off. A git that cannot answer counts as 0, so a
  # broken branch point never manufactures a body for an empty branch.
  ahead="$("$git" -C "$wt" rev-list --count origin/main..HEAD 2>/dev/null || echo 0)"
  case "$ahead" in ''|*[!0-9]*) ahead=0 ;; esac
  [ "$ahead" -ge 1 ] || return 1
  mkdir -p "$state/lanes" || return 1
  cat > "$fallback" <<EOF
## Symptom

Partial: the worker did not write state/lanes/$slug.pr-body.md; this body was generated by lane.sh after the worker exited. Verification evidence, if any, is in state/lanes/$n.worker.txt (not committed). The merge lane decides.

## Change

The worker committed its change before exiting; read git log origin/main..HEAD and the diff on the branch.

## Verification

The lane ran the same pre-push seams it runs for every hand-off. Evidence captured before the worker exited is in state/lanes/$n.worker.txt (not committed).

## Claims

Claim check: none: the worker did not write a claim before it exited (partial hand-off).

## Screenshots

none: the worker did not attach screenshots before it exited (partial hand-off).

## Risk

Partial hand-off: the worker's own summary is missing, so the merge lane and its reviewer must judge the diff on its own evidence.

RSI item: $item
EOF
  printf '%s\n' "$fallback"; return 0
}
